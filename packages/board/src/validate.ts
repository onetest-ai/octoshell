import { loadEntity, KIND_KEYS, KNOWN_KEYS, type EntityFields } from "./entity-schema.js";
import { readPointer, resolveWithin } from "./board-model.js";

export interface BoardFinding {
  mdPath: string;
  kind: EntityKind;
  severity: "error";
  message: string;
}

/**
 * A name is a placeholder if it's empty, a letter-prefixed sequence number,
 * a bare number, or a generic word. Ported verbatim from validate.js lines ~60-72.
 */
export function isPlaceholderName(raw: string): boolean {
  const s = (raw ?? "")
    .trim()
    .replace(/\*\*/g, "")
    .replace(/^\[[ xX]\]\s*/, "")
    .replace(/^\[(?:role|status|severity):[^\]]+\]\s*/i, "")
    .trim();
  if (!s) return true;
  if (/^[A-Za-z]{1,4}\d+(\.\d+)?$/.test(s)) return true; // T1, M3, T5.5, TSK12, C2
  if (/^\d+(\.\d+)?$/.test(s)) return true; // bare number
  if (/^(task|mission|campaign|bug|phase|step|item|untitled|tbd|todo|new\s+\w+)\s*\d*(\.\d+)?$/i.test(s)) return true;
  return false;
}

/** Body text of a `## <label>` section (until the next `## ` heading or the boundary comment). */
function sectionBody(text: string, label: string): string {
  const m = new RegExp(`^##\\s+${label}\\s*$`, "m").exec(text);
  if (!m) return "";
  const rest = text.slice(m.index + m[0].length);
  const ends = [rest.search(/^##\s+/m), rest.search(/^<!--/m)].filter((n) => n >= 0);
  return ends.length ? rest.slice(0, Math.min(...ends)) : rest;
}

function hasAcceptanceCriterion(text: string): boolean {
  return /^\s*-\s*\[[ xX]\]\s*\S/m.test(sectionBody(text, "Acceptance Criteria"));
}

/** Top-level (column-0) item titles under `## Tasks`. */
function taskNames(text: string): string[] {
  const lines = text.split("\n");
  const start = lines.findIndex((l) => /^##\s+Tasks\s*$/.test((l ?? "").trim()));
  if (start < 0) return [];
  const out: string[] = [];
  for (let i = start + 1; i < lines.length; i++) {
    const raw = lines[i] ?? "";
    if (/^##\s+/.test(raw.trim())) break;
    const mLine = raw.match(/^(?:\d+[.)]\s+|[-*]\s+)(.*)$/);
    if (mLine) out.push(mLine[1] ?? "");
  }
  return out;
}

/**
 * Validate a single brief's text. Pure and testable on a string.
 * Applies rules 1-5 from validate.js by kind.
 */
export function validateBriefText(kind: EntityKind, text: string, mdPath: string): BoardFinding[] {
  const findings: BoardFinding[] = [];
  const push = (message: string) => findings.push({ mdPath, kind, severity: "error", message });

  // Rule 1: title present and not a placeholder
  const titleM = /^#\s+(.+?)\s*$/m.exec(text);
  if (!titleM) {
    push("missing a `# Title` heading");
  } else {
    const title = (titleM[1] ?? "").trim();
    if (isPlaceholderName(title)) {
      push(
        `title "${title}" is just an id/placeholder — use the form \`<id> - descriptive name\` ` +
          `(e.g. "M3 - Skills workspace", "T3.1 - Add JWT validation to /login"); the bare id alone is not a name`,
      );
    }
  }

  // Rule 2: boundary comment present
  if (!text.includes("Auto-generated by Octobots") && !text.includes("Auto-generated by Octoshell")) {
    push("missing the `Auto-generated by Octobots` boundary comment");
  }

  // Rule 3: an agent-owned section present
  if (!/^##\s+(Tasks|Missions|Bugs)\s*$/m.test(text)) {
    push("missing an agent-owned `## Tasks`, `## Missions`, or `## Bugs` section");
  }

  // Rule 4: missions and tasks must carry at least one verifiable acceptance criterion
  if ((kind === "mission" || kind === "task") && !hasAcceptanceCriterion(text)) {
    push(
      "no acceptance criterion — add at least one checkable `- [ ]` item under `## Acceptance Criteria` " +
        "(use set-criterion.js); a task/mission without a verifiable acceptance criterion is not well-formed",
    );
  }

  // Rule 5: a mission's ## Tasks items must not be bare ids
  if (kind === "mission") {
    for (const name of taskNames(text)) {
      if (isPlaceholderName(name)) {
        push(
          `task "${name.trim()}" is just an id — use \`<id> - descriptive name\` ` +
            `(e.g. "T3.1 - Add JWT validation to /login"), not a bare "T1"/"T5.5"`,
        );
      }
    }
  }

  return findings;
}

function safeReaddir(dir: string): string[] {
  try {
    return readdirSync(dir);
  } catch {
    return [];
  }
}

function safeReadFile(filePath: string): string | null {
  try {
    return readFileSync(filePath, "utf8");
  } catch {
    return null;
  }
}

/** Validate a parsed YAML entity: a descriptive name, and (mission/task) ≥1 acceptance criterion. */
function validateEntityYaml(kind: EntityKind, fields: EntityFields, path: string): BoardFinding[] {
  const findings: BoardFinding[] = [];
  const push = (message: string): void => {
    findings.push({ mdPath: path, kind, severity: "error", message });
  };
  if (!fields.name.trim()) {
    push("missing a name");
  } else if (isPlaceholderName(fields.name)) {
    push(
      `title "${fields.name.trim()}" is just an id/placeholder — use the form \`<id> - descriptive name\` ` +
        `(e.g. "M3 - Skills workspace", "T3.1 - Add JWT validation to /login"); the bare id alone is not a name`,
    );
  }
  if ((kind === "mission" || kind === "task") && !fields.acceptanceCriteria.some((c) => c.text.trim())) {
    push(
      "no acceptance criterion — add at least one checkable acceptance criterion (use set-criterion.js); " +
        "a task/mission without a verifiable acceptance criterion is not well-formed",
    );
  }
  // A key this schema knows but this kind does not own. It is preserved across writes (nothing is
  // silently deleted) but the board never reads it, so it is reported rather than left to rot.
  // `kind` here is the wider managed-block union; only the four YAML kinds have a key list.
  const owned: readonly string[] | undefined = KIND_KEYS[kind as keyof typeof KIND_KEYS];
  for (const key of owned ? Object.keys(fields.extra ?? {}) : []) {
    if (!KNOWN_KEYS.has(key) || owned!.includes(key)) continue;
    push(`\`${key}\` is not a ${kind} field (${owningKinds(key)}) — it is preserved on disk but the board ignores it`);
  }

  // Criteria appended as prose into `notes` instead of written to `acceptance_criteria`: they read
  // fine to a human but the board never sees them as criteria. Bugs carry no criteria, so a
  // checkbox in a bug's notes is a legitimate repro checklist.
  if (kind !== "bug") {
    const stranded = strandedCriteria(fields.notes);
    if (stranded.length) {
      push(
        `${stranded.length} acceptance criterion-shaped line(s) stranded in \`notes\` ` +
          `(first: "${stranded[0]}") — notes are free-form prose the board never reads as criteria; ` +
          "move them into `acceptance_criteria` with set-criterion.js and never append them by hand",
      );
    }
  }
  return findings;
}

/** Human-readable list of the kinds that DO own `key`, for the misplaced-field message. */
function owningKinds(key: string): string {
  const kinds = (Object.keys(KIND_KEYS) as Array<keyof typeof KIND_KEYS>).filter((k) => KIND_KEYS[k].includes(key));
  return kinds.length ? `${kinds.join("/")} only` : "no kind uses it";
}

/**
 * Checkbox lines sitting in an entity's free-form `notes` — acceptance criteria that were appended
 * as text instead of written through the parser. Returns their texts.
 * Mirrors the pack's `scripts/validate.js` `strandedCriteria` — keep the two in step.
 */
export function strandedCriteria(notes: string | undefined): string[] {
  const out: string[] = [];
  for (const line of (notes ?? "").split("\n")) {
    const m = line.match(/^\s*[-*]\s*\[[ xX]\]\s*(\S.*)$/);
    if (m) out.push((m[1] ?? "").trim());
  }
  return out;
}

/** Validate one entity, preferring its `<kind>.yaml` and falling back to a legacy `<kind>.md`. */
function validateFile(filePath: string, kind: EntityKind): BoardFinding[] {
  const yamlPath = filePath.replace(/\.md$/, ".yaml");
  const yamlText = safeReadFile(yamlPath);
  if (yamlText !== null) return validateEntityYaml(kind, loadEntity(yamlText), yamlPath);
  const text = safeReadFile(filePath);
  if (text === null) return [];
  return validateBriefText(kind, text, filePath);
}

/**
 * Walk every .md under .octobots/ and aggregate findings.
 * Covers:
 *   campaigns/<id>/campaign.md
 *   campaigns/<id>/missions/<id>/mission.md
 *   campaigns/<id>/missions/<id>/tasks/<id>/task.md
 *   campaigns/<id>/missions/<id>/bugs/<id>/bug.md
 *   campaigns/<id>/bugs/<id>/bug.md
 */
/**
 * Validate one workflow folder against its `workflow.js` — the script is both the source of truth
 * and the file a human opens, so every finding anchors on it.
 */
export function validateWorkflow(jsPath: string, folderSlug: string): BoardFinding[] {
  const out: BoardFinding[] = [];
  const err = (message: string): void => {
    out.push({ mdPath: jsPath, kind: "workflow", severity: "error", message });
  };

  if (!existsSync(jsPath)) {
    err("workflow.js is missing");
    return out;
  }

  const source = readFileSync(jsPath, "utf8");
  let meta;
  try {
    meta = parseWorkflowMeta(source);
  } catch (e) {
    err((e as Error).message);
    return out;
  }

  if (meta.name !== folderSlug) {
    err(`meta.name "${meta.name}" does not match its folder "${folderSlug}"`);
  }
  // The declared graph is GENERATED from the body, so its internal consistency is not a thing to
  // check — it is a thing that cannot be wrong. What can be wrong is the body: whether it parses,
  // whether meta was regenerated after the last edit, and whether every agent() call actually
  // dispatches to the agent the diagram names. Checked ahead of `meta.phases.length` so a body
  // that fails to parse is reported even when meta happens to declare zero phases.
  let extracted;
  try {
    extracted = extractPhases(source);
  } catch (e) {
    err(`body does not parse: ${(e as Error).message}`);
    return out;
  }

  if (meta.phases.length === 0) {
    err("workflow has no phases");
    return out;
  }

  // Compare through the real writer/reader, not the raw extraction — serializeMeta writes each
  // step with JSON.stringify(step), so key INSERTION order becomes file order, while
  // parseWorkflowMeta rebuilds steps through coerceStep in its own canonical order. Comparing
  // extracted.phases against meta.phases directly would flag a perfectly current file as stale
  // over key order alone; round-tripping through the same writer+reader a real regenerate would
  // use makes this immune to that.
  const roundTripped = parseWorkflowMeta(
    `export const meta = ${serializeMeta({ name: meta.name, description: meta.description, phases: extracted.phases })}`,
  ).phases;
  if (JSON.stringify(roundTripped) !== JSON.stringify(meta.phases)) {
    err("meta is out of date — regenerate it with sync-meta.js");
  }
  for (const call of extracted.unclassified) {
    err(`line ${call.line}: ${call.callee}() has no readable label`);
  }
  for (const step of extracted.phases.flatMap((p) => p.steps)) {
    if (step.kind === "workflow") continue;
    if (!step.agent) err(`step "${step.id}" (${step.label}) has no agentType — it runs as the default subagent`);
  }

  return out;
}

/** Build the `BoardFinding` shape this file pushes for a workflow-folder problem. */
function workflowFinding(mdPath: string, message: string): BoardFinding {
  return { mdPath, kind: "workflow", severity: "error", message };
}

/** Validate every workflow folder under an entity, returning the count found. */
function validateWorkflowsUnder(entityDir: string, findings: BoardFinding[], root: string): number {
  const dir = join(entityDir, "workflows");
  let count = 0;
  for (const slug of safeReaddir(dir)) {
    const jsPath = join(dir, slug, "workflow.js");
    if (!existsSync(jsPath)) {
      // A folder may point at a shared pipeline instead of owning a script.
      const pointerPath = join(dir, slug, "workflow.json");
      if (!existsSync(pointerPath)) continue; // neither workflow.js nor a pointer → not a workflow folder
      count++;
      const uses = readPointer(pointerPath);
      const from = relative(root, join(dir, slug)).split(sep).join("/");
      const target = uses === null ? null : resolveWithin(from, uses);
      if (uses === null) {
        findings.push(workflowFinding(pointerPath, "workflow.json has no `uses` string"));
      } else if (target === null) {
        findings.push(workflowFinding(pointerPath, `pointer "${uses}" resolves outside the board`));
      } else if (!existsSync(join(root, target, "workflow.js"))) {
        findings.push(workflowFinding(pointerPath, `pointer "${uses}" names a folder with no workflow.js`));
      }
      continue;
    }
    count++;
    findings.push(...validateWorkflow(jsPath, slug));
  }
  return count;
}

export function validateBoard(root: string): BoardFinding[] {
  const findings: BoardFinding[] = [];
  const octobots = join(root, ".octobots");
  const campaigns = join(octobots, "campaigns");

  for (const campaignId of safeReaddir(campaigns)) {
    const campaignDir = join(campaigns, campaignId);

    // campaign.md
    findings.push(...validateFile(join(campaignDir, "campaign.md"), "campaign"));
    validateWorkflowsUnder(campaignDir, findings, octobots);

    // campaign-level bugs
    const campaignBugs = join(campaignDir, "bugs");
    for (const bugId of safeReaddir(campaignBugs)) {
      findings.push(...validateFile(join(campaignBugs, bugId, "bug.md"), "bug"));
    }

    // missions
    const missionsDir = join(campaignDir, "missions");
    for (const missionId of safeReaddir(missionsDir)) {
      const missionDir = join(missionsDir, missionId);

      // mission.md
      findings.push(...validateFile(join(missionDir, "mission.md"), "mission"));
      // A mission may hold SEVERAL workflows, one per execution loop
      // (implementation / testing / fixing) — they take different inputs, apply
      // different gates, and run at different times, and the acceptance loop
      // re-runs long after implementation is done. `workflowsByMission` in
      // `board-model.ts` has always been a `string[]`, keyed identically to the
      // campaign case; the cardinality rule that used to live here contradicted
      // the model it was validating. See onetest-ai/octoshell#60.
      validateWorkflowsUnder(missionDir, findings, octobots);

      // mission tasks
      const tasksDir = join(missionDir, "tasks");
      for (const taskId of safeReaddir(tasksDir)) {
        findings.push(...validateFile(join(tasksDir, taskId, "task.md"), "task"));
      }

      // mission-level bugs
      const missionBugs = join(missionDir, "bugs");
      for (const bugId of safeReaddir(missionBugs)) {
        findings.push(...validateFile(join(missionBugs, bugId, "bug.md"), "bug"));
      }
    }
  }

  return findings;
}
