import { describe, it, expect } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { BoardHost } from "../src/host/board-host.js";
import { runMissionDone, missionGuardApplies } from "../src/host/mission-done.js";
import { mkdtempClean } from "./fixtures/tmpdir.js";

const scriptPath = resolve(__dirname, "../resources/octobots-pack/skill/mission-planner/scripts/set-status.js");

function setup() {
  const repoRoot = mkdtempClean("mission-done-");
  const git = (...a: string[]) => execFileSync("git", a, { cwd: repoRoot, stdio: "ignore" });
  git("init", "-q");
  git("config", "user.email", "t@t.t");
  git("config", "user.name", "t");
  const board = new BoardHost(join(repoRoot, ".octobots"));
  const camp = board.createCampaign({ name: "Camp" });
  const mission = board.createMission({ title: "Mish", campaignId: camp.id });
  git("add", "-A");
  git("commit", "-qm", "init", "--allow-empty");
  const opts = { board, workspaceFolderPath: repoRoot, scriptPath, nodePath: process.execPath, env: process.env };
  return { repoRoot, board, mission, opts };
}

describe("runMissionDone", () => {
  it("refuses a mission with no gate records", async () => {
    const { opts, mission } = setup();
    const res = await runMissionDone(opts, mission.id);
    expect(res.ok).toBe(false);
    if (!res.ok) expect(res.message).toContain("refusing to mark");
  });

  it("with force marks the mission done on disk", async () => {
    const { opts, mission, board } = setup();
    const res = await runMissionDone(opts, mission.id, "test force");
    expect(res).toEqual({ ok: true });
    expect(board.getMission(mission.id)?.status).toBe("done");
  });
});

describe("runMissionDone with a campaign named like the mission", () => {
  it("guards the mission, never the same-titled campaign", async () => {
    const repoRoot = mkdtempClean("mission-done-same-");
    const git = (...a: string[]) => execFileSync("git", a, { cwd: repoRoot, stdio: "ignore" });
    git("init", "-q");
    git("config", "user.email", "t@t.t");
    git("config", "user.name", "t");
    const board = new BoardHost(join(repoRoot, ".octobots"));
    const camp = board.createCampaign({ name: "Mish" });
    const mission = board.createMission({ title: "Mish", campaignId: camp.id });
    git("add", "-A");
    git("commit", "-qm", "init", "--allow-empty");
    const campStatus = board.getCampaign(camp.id)?.status;
    const opts = { board, workspaceFolderPath: repoRoot, scriptPath, nodePath: process.execPath, env: process.env };

    const refused = await runMissionDone(opts, mission.id);
    expect(refused.ok).toBe(false);
    if (!refused.ok) expect(refused.message).toContain("refusing to mark");
    board.reconcile();
    expect(board.getCampaign(camp.id)?.status).toBe(campStatus);
    expect(board.getMission(mission.id)?.status).not.toBe("done");

    expect(await runMissionDone(opts, mission.id, "test force")).toEqual({ ok: true });
    expect(board.getMission(mission.id)?.status).toBe("done");
    expect(board.getCampaign(camp.id)?.status).toBe(campStatus);
  });
});

describe("runMissionDone with a legacy mission.md mission", () => {
  it("targets the mission folder, so the gate refuses (exit 3) instead of failing on a missing mission.yaml", async () => {
    const repoRoot = mkdtempClean("mission-done-legacy-");
    const git = (...a: string[]) => execFileSync("git", a, { cwd: repoRoot, stdio: "ignore" });
    git("init", "-q");
    git("config", "user.email", "t@t.t");
    git("config", "user.name", "t");
    const cDir = join(repoRoot, ".octobots", "campaigns", "q3");
    const mDir = join(cDir, "missions", "m1-skills");
    mkdirSync(mDir, { recursive: true });
    writeFileSync(join(cDir, "campaign.md"), "# Q3\n\n## Description\nx\n\n<!-- Auto-generated by Octobots -->\n## Missions\n- [status:executing] M1 - Skills\n");
    writeFileSync(join(mDir, "mission.md"), "# M1 - Skills\n\n## Description\nd\n\n## Acceptance Criteria\n- [ ] ac\n\n<!-- Auto-generated by Octobots -->\n## Tasks\n_(none)_\n");
    git("add", "-A");
    git("commit", "-qm", "init");
    const board = new BoardHost(join(repoRoot, ".octobots"));
    const campaignId = board.boardModel.listCampaigns()[0]!.id;
    const mission = board.boardModel.listMissions(campaignId)[0]!;
    const opts = { board, workspaceFolderPath: repoRoot, scriptPath, nodePath: process.execPath, env: process.env };
    const res = await runMissionDone(opts, mission.id);
    expect(res.ok).toBe(false);
    if (!res.ok) expect(res.message).toContain("refusing to mark");
  });
});

describe("runMissionDone when the reconcile after a successful run throws", () => {
  it("rejects instead of leaving the promise unsettled", async () => {
    const { opts, mission, board } = setup();
    board.reconcile = () => { throw new Error("reconcile broke"); };
    await expect(runMissionDone(opts, mission.id, "test force")).rejects.toThrow("reconcile broke");
  });
});

describe("missionGuardApplies", () => {
  function primer(ws: string, v: number) {
    mkdirSync(join(ws, ".octobots", "hooks"), { recursive: true });
    writeFileSync(join(ws, ".octobots", "hooks", "primer.mjs"), `// octobots-pack-version: ${v}\n`);
  }
  it("is true for 65, false for 64 and for a missing primer", () => {
    const a = mkdtempClean("guard-a-"); primer(a, 65);
    const b = mkdtempClean("guard-b-"); primer(b, 64);
    expect(missionGuardApplies(a)).toBe(true);
    expect(missionGuardApplies(b)).toBe(false);
    expect(missionGuardApplies(mkdtempClean("guard-c-"))).toBe(false);
  });
});
