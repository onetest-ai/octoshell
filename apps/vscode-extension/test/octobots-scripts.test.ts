describe("create-team.js", () => {
  const baseArgs = [
    "--id", "team-web",
    "--title", "Web Team",
    "--backend", "claude",
    "--roster", "frontend,backend",
  ];

  it("creates a team marker with correct schema (no description)", () => {
    const r = run("create-team.js", baseArgs, repo);
    expect(r.code).toBe(0);
    expect(r.out).toContain("created team: team-web");

    const markerPath = join(repo, ".octobots", "teams", "team-web.json");
    const marker = JSON.parse(readFileSync(markerPath, "utf8"));
    expect(marker).toEqual({
      id: "team-web",
      title: "Web Team",
      backend: "claude",
      roster: ["frontend", "backend"],
    });
    expect(Object.prototype.hasOwnProperty.call(marker, "description")).toBe(false);
  });

  it("creates a team marker with description when --description provided", () => {
    const r = run("create-team.js", [...baseArgs, "--description", "Handles the web frontend"], repo);
    expect(r.code).toBe(0);

    const markerPath = join(repo, ".octobots", "teams", "team-web.json");
    const marker = JSON.parse(readFileSync(markerPath, "utf8"));
    expect(marker.description).toBe("Handles the web frontend");
    expect(marker.id).toBe("team-web");
    expect(marker.roster).toEqual(["frontend", "backend"]);
  });

  it("rejects an invalid --backend (exit 2)", () => {
    const r = run(
      "create-team.js",
      ["--id", "t", "--title", "T", "--backend", "openai", "--roster", "dev"],
      repo,
    );
    expect(r.code).toBe(2);
    expect(r.out.toLowerCase()).toContain("backend");
  });

  it("rejects a non-slug --id (exit 2)", () => {
    const r = run(
      "create-team.js",
      ["--id", "My Team!", "--title", "T", "--backend", "claude", "--roster", "dev"],
      repo,
    );
    expect(r.code).toBe(2);
    expect(r.out.toLowerCase()).toContain("id");
  });

  it("rejects an empty --roster (exit 2)", () => {
    const r = run(
      "create-team.js",
      ["--id", "t", "--title", "T", "--backend", "claude", "--roster", ""],
      repo,
    );
    expect(r.code).toBe(2);
    expect(r.out.toLowerCase()).toContain("roster");
  });

  it("refuses to overwrite an existing marker without --force (exit 1)", () => {
    run("create-team.js", baseArgs, repo);
    const r = run("create-team.js", baseArgs, repo);
    expect(r.code).toBe(1);
    expect(r.out).toContain("already exists");
    expect(r.out).toContain("--force");
  });

  it("overwrites an existing marker with --force (exit 0)", () => {
    run("create-team.js", baseArgs, repo);
    const r = run("create-team.js", [...baseArgs, "--title", "Web Team v2", "--force"], repo);
    expect(r.code).toBe(0);

    const markerPath = join(repo, ".octobots", "teams", "team-web.json");
    const marker = JSON.parse(readFileSync(markerPath, "utf8"));
    expect(marker.title).toBe("Web Team v2");
  });

  it("warns about an uninstalled role but still writes the marker (exit 0)", () => {
    const r = run(
      "create-team.js",
      ["--id", "team-ops", "--title", "Ops", "--backend", "copilot", "--roster", "ghost-role"],
      repo,
    );
    expect(r.code).toBe(0);
    expect(r.out.toLowerCase()).toContain("warning");
    expect(r.out.toLowerCase()).toContain("ghost-role");

    const markerPath = join(repo, ".octobots", "teams", "team-ops.json");
    const marker = JSON.parse(readFileSync(markerPath, "utf8"));
    expect(marker.roster).toEqual(["ghost-role"]);
  });

  it("does not warn about an installed role", () => {
    // simulate all roster roles installed as agent dirs
    mkdirSync(join(repo, ".claude", "agents", "frontend"), { recursive: true });
    mkdirSync(join(repo, ".claude", "agents", "backend"), { recursive: true });
    const r = run("create-team.js", baseArgs, repo);
    expect(r.code).toBe(0);
    expect(r.out).not.toContain("warning");
  });

  it("exits 2 when required args are missing", () => {
    const r = run("create-team.js", ["--id", "t"], repo);
    expect(r.code).toBe(2);
    expect(r.out.toLowerCase()).toContain("usage");
  });
});

describe("delete-bug.js", () => {
  it("removes the ## Bugs line AND trashes the bug folder", () => {
    const campaignMd = join(repo, ".octobots", "campaigns", "c", "campaign.md");
    const bugDir = join(repo, ".octobots", "campaigns", "c", "bugs", "boom");
    mkdirSync(bugDir, { recursive: true });
    writeFileSync(campaignMd, "# C\n\n<!-- Auto-generated by Octobots ... -->\n## Bugs\n- [status:done] Boom on save\n- Keep me\n", "utf8");
    writeFileSync(join(bugDir, "bug.md"), "# Boom on save\n\n## Severity\nmajor\n", "utf8");

    const r = run("delete-bug.js", [campaignMd, "Boom on save"], repo);
    expect(r.code).toBe(0);
    const md = readFileSync(campaignMd, "utf8");
    expect(md).not.toContain("Boom on save");
    expect(md).toContain("Keep me");
    expect(existsSync(bugDir)).toBe(false);
    expect(existsSync(join(repo, ".octobots", ".trash", "boom"))).toBe(true);
  });

  it("exits 1 when no matching bug exists", () => {
    const campaignMd = join(repo, ".octobots", "campaigns", "c", "campaign.md");
    writeFileSync(campaignMd, "# C\n\n<!-- Auto-generated by Octobots ... -->\n## Bugs\n- Other\n", "utf8");
    expect(run("delete-bug.js", [campaignMd, "Nope"], repo).code).toBe(1);
  });
});

