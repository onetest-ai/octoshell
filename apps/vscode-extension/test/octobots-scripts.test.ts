import { describe, it, expect, beforeEach } from "vitest";
import { spawnSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const SCRIPTS = join(__dirname, "..", "resources", "octobots-pack", "skill", "mission-planner", "scripts");
function run(script: string, args: string[], cwd: string): { out: string; code: number } {
  const result = spawnSync("node", [join(SCRIPTS, script), ...args], { cwd, encoding: "utf8" });
  const out = `${result.stdout ?? ""}${result.stderr ?? ""}`;
  const code = result.status ?? 1;
  return { out, code };
}

let repo: string;
let missionMd: string;
const GOOD =
  "# M\n\n## Description\nd\n\n## Acceptance Criteria\n- [ ] one\n- [x] two\n\n## Sessions\n_(no execution sessions yet)_\n\n" +
  "<!-- Auto-generated by Octobots ... -->\n## Tasks\n- Existing task\n";

beforeEach(() => {
  repo = mkdtempSync(join(tmpdir(), "octobots-scripts-"));
  missionMd = join(repo, ".octobots", "campaigns", "c", "missions", "m", "mission.md");
  mkdirSync(join(repo, ".octobots", "campaigns", "c", "missions", "m"), { recursive: true });
  writeFileSync(missionMd, GOOD, "utf8");
});

describe("validate.js", () => {
  it("passes a well-formed board (exit 0)", () => {
    expect(run("validate.js", [missionMd], repo).code).toBe(0);
  });
  it("fails a board missing the Octobots boundary comment (exit non-zero)", () => {
    writeFileSync(missionMd, "# M\n## Tasks\n- x\n", "utf8");
    const r = run("validate.js", [missionMd], repo);
    expect(r.code).not.toBe(0);
    expect(r.out.toLowerCase()).toContain("auto-generated");
  });

  it("rejects a placeholder task title like 'T1' (exit 1)", () => {
    const taskMd = join(repo, ".octobots", "campaigns", "c", "missions", "m", "tasks", "t1", "task.md");
    mkdirSync(join(repo, ".octobots", "campaigns", "c", "missions", "m", "tasks", "t1"), { recursive: true });
    writeFileSync(taskMd, "# T1\n\n## Acceptance Criteria\n- [ ] does the thing\n\n<!-- Auto-generated by Octobots ... -->\n## Tasks\n_(none)_\n", "utf8");
    const r = run("validate.js", [taskMd], repo);
    expect(r.code).toBe(1);
    expect(r.out.toLowerCase()).toContain("placeholder");
  });

  it("rejects a task with no acceptance criteria (exit 1)", () => {
    const taskMd = join(repo, ".octobots", "campaigns", "c", "missions", "m", "tasks", "wire-auth", "task.md");
    mkdirSync(join(repo, ".octobots", "campaigns", "c", "missions", "m", "tasks", "wire-auth"), { recursive: true });
    writeFileSync(taskMd, "# Wire up auth\n\n## Acceptance Criteria\n_(not set)_\n\n<!-- Auto-generated by Octobots ... -->\n## Tasks\n_(none)_\n", "utf8");
    const r = run("validate.js", [taskMd], repo);
    expect(r.code).toBe(1);
    expect(r.out.toLowerCase()).toContain("acceptance criteria");
  });

  it("passes a well-formed task (descriptive name + acceptance criterion)", () => {
    const taskMd = join(repo, ".octobots", "campaigns", "c", "missions", "m", "tasks", "wire-auth", "task.md");
    mkdirSync(join(repo, ".octobots", "campaigns", "c", "missions", "m", "tasks", "wire-auth"), { recursive: true });
    writeFileSync(taskMd, "# Add JWT validation to /login\n\n## Acceptance Criteria\n- [ ] rejects an expired token\n\n<!-- Auto-generated by Octobots ... -->\n## Tasks\n_(none)_\n", "utf8");
    expect(run("validate.js", [taskMd], repo).code).toBe(0);
  });

  it("flags a placeholder-named task in a mission's ## Tasks block", () => {
    writeFileSync(missionMd, GOOD.replace("- Existing task", "- Existing task\n- T5.5"), "utf8");
    const r = run("validate.js", [missionMd], repo);
    expect(r.code).toBe(1);
    expect(r.out).toContain("T5.5");
  });

  it("accepts the `<id> - name` title format (id prefix + descriptive name)", () => {
    const taskMd = join(repo, ".octobots", "campaigns", "c", "missions", "m", "tasks", "t31", "task.md");
    mkdirSync(join(repo, ".octobots", "campaigns", "c", "missions", "m", "tasks", "t31"), { recursive: true });
    writeFileSync(taskMd, "# T3.1 - Add JWT validation to /login\n\n## Acceptance Criteria\n- [ ] rejects expired tokens\n\n<!-- Auto-generated by Octobots ... -->\n## Tasks\n_(none)_\n", "utf8");
    expect(run("validate.js", [taskMd], repo).code).toBe(0);
    // And an `<id> - name` line inside a mission's ## Tasks is not flagged.
    writeFileSync(missionMd, GOOD.replace("- Existing task", "- T1.1 - Wire the API client"), "utf8");
    expect(run("validate.js", [missionMd], repo).code).toBe(0);
  });
});

describe("add-doc.js", () => {
  const WITH_DOCS =
    "# C\n\n## Description\nd\n\n## Acceptance Criteria\n- [ ] one\n\n## Documents\n_(none)_\n\n## Sessions\n_(no execution sessions yet)_\n\n" +
    "<!-- Auto-generated by Octobots ... -->\n## Missions\n- A mission\n";
  let campaignMd: string;
  beforeEach(() => {
    campaignMd = join(repo, ".octobots", "campaigns", "c", "campaign.md");
    writeFileSync(campaignMd, WITH_DOCS, "utf8");
  });

  it("replaces the _(none)_ placeholder with a `- [label](target)` link line", () => {
    const r = run("add-doc.js", [campaignMd, "M1 spec", "docs/superpowers/specs/foo.md"], repo);
    expect(r.code).toBe(0);
    const text = readFileSync(campaignMd, "utf8");
    expect(text).toContain("- [M1 spec](docs/superpowers/specs/foo.md)");
    expect(text).not.toContain("_(none)_");
    expect(text.indexOf("## Documents")).toBeLessThan(text.indexOf("## Sessions")); // stayed in its section
  });

  it("appends a second link without dropping the first", () => {
    run("add-doc.js", [campaignMd, "Spec", "docs/a.md"], repo);
    run("add-doc.js", [campaignMd, "Plan", "docs/b.md"], repo);
    const text = readFileSync(campaignMd, "utf8");
    expect(text).toContain("- [Spec](docs/a.md)");
    expect(text).toContain("- [Plan](docs/b.md)");
  });

  it("is idempotent on the target (no duplicate)", () => {
    run("add-doc.js", [campaignMd, "Spec", "docs/a.md"], repo);
    const r = run("add-doc.js", [campaignMd, "Renamed", "docs/a.md"], repo);
    expect(r.code).toBe(0);
    expect(r.out).toContain("already present");
    expect(readFileSync(campaignMd, "utf8").match(/docs\/a\.md/g)).toHaveLength(1);
  });

  it("errors when there is no ## Documents section (task boards)", () => {
    const r = run("add-doc.js", [missionMd, "X", "docs/x.md"], repo);
    expect(r.code).not.toBe(0);
    expect(r.out).toContain("Documents");
  });
});

describe("add-task.js", () => {
  it("appends a task under ## Tasks without touching the managed header", () => {
    const r = run("add-task.js", [missionMd, "Ship it"], repo);
    expect(r.code).toBe(0);
    const text = readFileSync(missionMd, "utf8");
    expect(text).toContain("- Existing task");
    expect(text).toContain("- Ship it");
    expect(text).toContain("Auto-generated by Octobots");
    expect(text.indexOf("## Description")).toBeLessThan(text.indexOf("## Tasks"));
  });
  it("replaces the empty placeholder line", () => {
    writeFileSync(missionMd, GOOD.replace("- Existing task", "_(none yet — the planner proposes tasks here)_"), "utf8");
    run("add-task.js", [missionMd, "First"], repo);
    const text = readFileSync(missionMd, "utf8");
    expect(text).toContain("- First");
    expect(text).not.toContain("_(none yet");
  });
  it("writes [role:<name>] marker when --role is provided", () => {
    const r = run("add-task.js", [missionMd, "Build API", "--role", "tech-lead"], repo);
    expect(r.code).toBe(0);
    const text = readFileSync(missionMd, "utf8");
    expect(text).toContain("- [role:tech-lead] Build API");
  });
  it("writes plain line (no role marker) when --role is absent", () => {
    const r = run("add-task.js", [missionMd, "Build UI"], repo);
    expect(r.code).toBe(0);
    const text = readFileSync(missionMd, "utf8");
    expect(text).toContain("- Build UI");
    expect(text).not.toContain("[role:");
  });
  it("--role flag replaces the empty placeholder with the role marker", () => {
    writeFileSync(missionMd, GOOD.replace("- Existing task", "_(none yet — the planner proposes tasks here)_"), "utf8");
    const r = run("add-task.js", ["--role", "backend", missionMd, "First task"], repo);
    expect(r.code).toBe(0);
    const text = readFileSync(missionMd, "utf8");
    expect(text).toContain("- [role:backend] First task");
    expect(text).not.toContain("_(none yet");
  });

  it("creates a folder-backed task: tasks/<slug>/task.md with a clean heading (no octobots:id marker)", () => {
    run("add-task.js", [missionMd, "Wire the auth flow", "--role", "tech-lead"], repo);
    const taskMd = join(repo, ".octobots", "campaigns", "c", "missions", "m", "tasks", "wire-the-auth-flow", "task.md");
    expect(existsSync(taskMd)).toBe(true);
    const md = readFileSync(taskMd, "utf8");
    // Clean heading — no octobots:id marker; entities are identified by folder path.
    expect(md).toMatch(/^# Wire the auth flow\n\n/);
    expect(md).not.toContain("octobots:id");
    expect(md).toContain("## Acceptance Criteria");
    expect(md).toContain("Auto-generated by Octobots");
  });
});

