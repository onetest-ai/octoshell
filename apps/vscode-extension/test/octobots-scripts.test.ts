describe("set-status.js", () => {
  it("sets a [status:done] marker on a matching task line", () => {
    const r = run("set-status.js", [missionMd, "Existing task", "done"], repo);
    expect(r.code).toBe(0);
    expect(readFileSync(missionMd, "utf8")).toContain("- [status:done] Existing task");
  });

  it("is idempotent: re-setting status replaces (does not duplicate) the marker", () => {
    run("set-status.js", [missionMd, "Existing task", "done"], repo);
    run("set-status.js", [missionMd, "Existing task", "active"], repo);
    const text = readFileSync(missionMd, "utf8");
    expect(text).toContain("- [status:active] Existing task");
    expect(text).not.toContain("[status:done]");
    expect(text.match(/\[status:/g)).toHaveLength(1);
  });

  it("preserves an existing [severity:] marker on a bug line and appends/updates [status:]", () => {
    writeFileSync(missionMd, GOOD + "\n## Bugs\n- [severity:blocker] Crash on save\n", "utf8");
    const r = run("set-status.js", [missionMd, "Crash on save", "done"], repo);
    expect(r.code).toBe(0);
    const text = readFileSync(missionMd, "utf8");
    expect(text).toContain("[severity:blocker]");
    expect(text).toContain("[status:done]");
    expect(text).toContain("Crash on save");
  });

  it("accepts a multi-word state like 'awaiting approval'", () => {
    const r = run("set-status.js", [missionMd, "Existing task", "awaiting", "approval"], repo);
    expect(r.code).toBe(0);
    expect(readFileSync(missionMd, "utf8")).toContain("- [status:awaiting approval] Existing task");
  });

  it("rejects an unknown state (exit 2)", () => {
    const r = run("set-status.js", [missionMd, "Existing task", "bogus"], repo);
    expect(r.code).toBe(2);
    expect(r.out.toLowerCase()).toContain("invalid state");
  });

  it("exits 1 when no board line matches the title", () => {
    const r = run("set-status.js", [missionMd, "No such task", "done"], repo);
    expect(r.code).toBe(1);
    expect(r.out.toLowerCase()).toContain("no board line");
  });

  it("exits 2 when args are missing", () => {
    const r = run("set-status.js", [missionMd, "Existing task"], repo);
    expect(r.code).toBe(2);
    expect(r.out.toLowerCase()).toContain("usage");
  });

  describe("campaign self-status (## Status section)", () => {
    let campaignMd: string;
    const CAMPAIGN =
      "# My Campaign\n<!-- octobots:id abc123 -->\n\n## Status\ndraft\n\n## Target\nt\n\n## Description\nd\n\n" +
      "<!-- Auto-generated by Octobots ... -->\n## Missions\n- A mission\n";
    beforeEach(() => {
      campaignMd = join(repo, ".octobots", "campaigns", "c", "campaign.md");
      writeFileSync(campaignMd, CAMPAIGN, "utf8");
    });

    it("replaces the campaign's ## Status body when the title matches the campaign heading", () => {
      const r = run("set-status.js", [campaignMd, "My Campaign", "done"], repo);
      expect(r.code).toBe(0);
      const text = readFileSync(campaignMd, "utf8");
      expect(text).toContain("## Status\ndone");
      expect(text).not.toContain("## Status\ndraft");
      // Other sections + tail are untouched.
      expect(text).toContain("## Target\nt");
      expect(text).toContain("## Missions");
      expect(text).toContain("- A mission");
    });

    it("inserts a ## Status section when one is absent (after the id marker)", () => {
      writeFileSync(
        campaignMd,
        "# My Campaign\n<!-- octobots:id abc123 -->\n\n## Target\nt\n\n<!-- Auto-generated by Octobots ... -->\n## Missions\n- A mission\n",
        "utf8",
      );
      const r = run("set-status.js", [campaignMd, "My Campaign", "cancelled"], repo);
      expect(r.code).toBe(0);
      const text = readFileSync(campaignMd, "utf8");
      expect(text).toContain("## Status\ncancelled");
      expect(text.indexOf("## Status")).toBeLessThan(text.indexOf("## Target"));
    });

    it("falls back to the board-line path when the title does NOT match the campaign name", () => {
      const r = run("set-status.js", [campaignMd, "A mission", "executing"], repo);
      expect(r.code).toBe(0);
      const text = readFileSync(campaignMd, "utf8");
      expect(text).toContain("- [status:executing] A mission");
      expect(text).toContain("## Status\ndraft"); // campaign's own status untouched
    });
  });
});

