#!/usr/bin/env node
import { readFileSync, writeFileSync, existsSync, statSync, mkdirSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { randomUUID } from "node:crypto";

// Create a campaign: `<root>/campaigns/<slug>/campaign.md`. Disk is the source of truth — a campaign
// IS its folder, identified by its folder path (`folder:<relPath>`); no marker is written. This is
// the orchestrator's create tool, the peer of add-mission/add-task, so a board can be built head-
// lessly (no Octoshell UI). Optional `--description` / `--target` fill the managed fields; the
// campaign starts with an empty `## Missions` for add-mission.js to populate.
const rawArgs = process.argv.slice(2);
let description = "";
let target = "";
let root = ".octobots";
const positional = [];
for (let i = 0; i < rawArgs.length; i++) {
  if (rawArgs[i] === "--description") description = (rawArgs[++i] ?? "").trim();
  else if (rawArgs[i] === "--target") target = (rawArgs[++i] ?? "").trim();
  else if (rawArgs[i] === "--root") root = (rawArgs[++i] ?? "").trim() || ".octobots";
  else positional.push(rawArgs[i]);
}

const name = (positional[0] ?? "").trim();
if (!name) {
  console.error('usage: add-campaign.js "<name>" [--description <text>] [--target <text>] [--root <dir>]');
  process.exit(2);
}

const newId = () => randomUUID().replace(/-/g, "").slice(0, 12);
const slugify = (s) => {
  const out = s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 50).replace(/-+$/g, "");
  return out || newId().slice(0, 8);
};
const campaignsDir = join(root, "campaigns");
const taken = existsSync(campaignsDir)
  ? new Set(readdirSync(campaignsDir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name))
  : new Set();
let slug = slugify(name);
if (taken.has(slug)) { for (let n = 2; ; n++) { if (!taken.has(`${slug}-${n}`)) { slug = `${slug}-${n}`; break; } } }
const campaignDir = join(campaignsDir, slug);
mkdirSync(campaignDir, { recursive: true });

// `## Status` (settable, overrides the mission rollup when non-draft) and `## Target` are campaign-only
// managed fields; `## Missions` below the boundary is the orchestrator-owned section add-mission.js
// appends to. A `## Documents` section is not scaffolded here (matching createCampaign/add-task/
// add-bug) — add-doc.js creates it on demand when a document is first attached.
const campaignMd =
  `# ${name}\n\n` +
  `## Status\ndraft\n\n` +
  `## Target\n${target || "_(not set)_"}\n\n` +
  `## Description\n${description || "_(not set)_"}\n\n` +
  `## Acceptance Criteria\n_(not set)_\n\n` +
  `<!-- Auto-generated by Octobots from the campaign's fields above. The orchestrator owns any sections appended below this comment. -->\n` +
  `## Missions\n_(none yet — the orchestrator proposes missions here)_\n`;
writeFileSync(join(campaignDir, "campaign.md"), campaignMd, "utf8");
console.log(`added campaign: ${name} (campaigns/${slug})`);
